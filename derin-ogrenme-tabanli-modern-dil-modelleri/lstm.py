#%% text cleaning and preprocessing: tokenization, padding, label encoding

#tokenization
tokenizer = Tokenizer(char_level=True)
tokenizer.fit_on_texts(texts)

# Sözlük boyutunu görelim (kaç farklı karakter var?)
vocab_size = len(tokenizer.word_index) + 1
print("Karakter Sözlüğü:", tokenizer.word_index)
print("Vocab Size:", vocab_size)

# n-gram dizileri olustur ve padding uygula
input_sequences= []
for text in texts:
    #harfleri harf indekslerine çevir
    token_list = tokenizer.texts_to_sequences([text])[0]
    
    #her harf için ngram dizisi oluşturalım
    for i in range(1, len(token_list)):
        ngram_sequence = token_list[:i+1]
        input_sequences.append(ngram_sequence)

# en uzun diziyi bulalim, tum dizileri ayni uzunluga getirelim
max_sequence_length = max(len(x) for x in input_sequences)

# dizilere padding islemi uygula, hepsinin ayni uzunlukta olmasini sagla
input_sequences = pad_sequences(input_sequences, maxlen = max_sequence_length, padding = "pre")

# X(girdi) ve y(hedef degisken) 
X = input_sequences[:,:-1] 
y = input_sequences[:,-1]
 
y = tf.keras.utils.to_categorical(y, num_classes = vocab_size) # one hot encoding


#%% creating LSTM model, compiling, training and evaluation
model = Sequential()

# embedding
model.add(Embedding(vocab_size, 32, input_length = X.shape[1]))

# lstm
model.add(LSTM(100, return_sequences = False))

# dense
model.add(Dense(vocab_size,activation = "softmax"))

# model compile
model.compile(optimizer = "adam", loss = "categorical_crossentropy", metrics = ["accuracy"])

# model traninig
model.fit(X,y, epochs = 100, verbose = 1)

#model save
model.save("harf_lstm_modeli.keras")

#%% model prediction function and prediction examples

def generate_letter(seed_letter, next_letters):
    for _ in range(next_letters):
        #tokenization
        token_list= tokenizer.texts_to_sequences([seed_letter])[0]
        
        #padding
        token_list = pad_sequences([token_list], maxlen=max_sequence_length-1, padding = "pre")
        
        #predict
        predicted_prob= model.predict(token_list, verbose=0)
        
        #max prob
        predicted_letter_index = np.argmax(predicted_prob, axis = -1)
        
        #tokenizer ile harfi bul
        predicted_letter = tokenizer.index_word[predicted_letter_index[0]]
                
        # tahmin edilen harfi seed_text e ekleyelim 
        seed_letter = seed_letter + predicted_letter
        
    return seed_letter
        
        
